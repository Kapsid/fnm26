/// Where Greenland's 80 fringe ids start. A fixed range, clear of the seeded
/// fringe (10 000 000 up to about 10 017 000), staff (900M+), golden cohorts
/// (950M+) and newgens (1e9+): ids computed off the end of the shared fringe
/// sequence could collide with a surviving nation's fringe in an old database
/// that had nations pruned.
const int greenlandFringeFirstId = 20212000;

/// Greenland's whole stored pool: the squad plus its generated fringe
/// (ids 20212000 to 20212079), with clubs assigned the way
/// [PoolGenerator.expand] assigns them to every seeded squad.
List<Player> greenlandPool() => [
  for (final p in greenlandSquad) PoolGenerator.withClub(p),
  ...PoolGenerator.fringeFor(
    nationId: DormantNations.greenlandId,
    squad: greenlandSquad,
    firstId: greenlandFringeFirstId,
    names: (first: greenlandFringeFirstNames, sur: greenlandFringeSurnames),
  ),
];
